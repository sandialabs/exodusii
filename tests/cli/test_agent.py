"""Tests for ``python -m exodusii agent bootstrap``."""

import io
import json
from pathlib import Path

import pytest

from exodusii.agent import write_agent_bootstrap
from exodusii.agent.bootstrap import CLAUDE_GUIDANCE_BEGIN
from exodusii.agent.bootstrap import CLAUDE_GUIDANCE_END
from exodusii.agent.bootstrap import CORE_BOOTSTRAP_SKILLS
from exodusii.cli.learn import load_skill_dataset
from exodusii.cli.main import main

SKILLS = sorted(load_skill_dataset())


def _files(root: Path) -> set[str]:
    return {str(p.relative_to(root)) for p in root.rglob("*") if p.is_file()}


def _run_json(argv: list[str]) -> tuple[int, dict]:
    stream = io.StringIO()
    code = main(argv, file=stream)
    return code, json.loads(stream.getvalue())


def test_core_bootstrap_skills_are_installed() -> None:
    assert set(CORE_BOOTSTRAP_SKILLS) <= set(SKILLS)


def test_generic_writes_bootstrap_index_and_skills(tmp_path: Path) -> None:
    write_agent_bootstrap("generic", root=tmp_path)

    root = ".agent/exodusii"
    expected = {f"{root}/BOOTSTRAP.md", f"{root}/INDEX.md"}
    expected |= {f"{root}/skills/{name}.md" for name in SKILLS}
    assert _files(tmp_path) == expected

    bootstrap = (tmp_path / root / "BOOTSTRAP.md").read_text()
    assert bootstrap.startswith("# exodusii Agent Bootstrap\n")
    assert "python -m exodusii learn capabilities overview" in bootstrap
    assert "Database-First Rule" in bootstrap
    for name in SKILLS:
        assert f"`{name}`" in bootstrap
    assert "@@" not in bootstrap

    index = (tmp_path / root / "INDEX.md").read_text()
    assert index.startswith("# exodusii Agent Guide\n")
    assert "Generated by `python -m exodusii agent bootstrap`." in index


def test_skill_files_round_trip_skill_dataset(tmp_path: Path) -> None:
    import yaml

    write_agent_bootstrap("generic", root=tmp_path)
    data = load_skill_dataset()
    for name in SKILLS:
        text = (tmp_path / ".agent/exodusii/skills" / f"{name}.md").read_text()
        _, frontmatter, body = text.split("---\n", 2)
        meta = yaml.safe_load(frontmatter)
        assert meta == {"name": name, "description": data[name]["description"]}
        assert body.lstrip("\n").rstrip("\n") == data[name]["body"].rstrip("\n")


def test_generic_brief_writes_only_bootstrap(tmp_path: Path) -> None:
    write_agent_bootstrap("generic", brief=True, root=tmp_path)
    assert _files(tmp_path) == {".agent/exodusii/BOOTSTRAP.md"}


def test_opencode_writes_generic_and_skill_layout(tmp_path: Path) -> None:
    write_agent_bootstrap("opencode", root=tmp_path)
    files = _files(tmp_path)
    assert ".agent/exodusii/BOOTSTRAP.md" in files
    assert ".agent/exodusii/INDEX.md" in files
    for name in SKILLS:
        assert f".opencode/skills/{name}/SKILL.md" in files


def test_opencode_brief_writes_generic_bootstrap_only(tmp_path: Path) -> None:
    write_agent_bootstrap("opencode", brief=True, root=tmp_path)
    assert _files(tmp_path) == {".agent/exodusii/BOOTSTRAP.md"}


def test_claude_writes_claude_md_and_skill_layout(tmp_path: Path) -> None:
    write_agent_bootstrap("claude", root=tmp_path)

    expected = {"CLAUDE.md"} | {f".claude/skills/{name}/SKILL.md" for name in SKILLS}
    assert _files(tmp_path) == expected

    guidance = (tmp_path / "CLAUDE.md").read_text()
    assert guidance.startswith(CLAUDE_GUIDANCE_BEGIN)
    assert guidance.rstrip().endswith(CLAUDE_GUIDANCE_END)
    assert ".claude/skills/<skill-name>/SKILL.md" in guidance
    for name in CORE_BOOTSTRAP_SKILLS:
        assert f"- `{name}`\n" in guidance
    assert "@@" not in guidance


def test_claude_brief_writes_only_claude_md(tmp_path: Path) -> None:
    write_agent_bootstrap("claude", brief=True, root=tmp_path)
    assert _files(tmp_path) == {"CLAUDE.md"}


def test_claude_refuses_existing_claude_md(tmp_path: Path) -> None:
    (tmp_path / "CLAUDE.md").write_text("# Project notes\n")
    with pytest.raises(FileExistsError, match="--append"):
        write_agent_bootstrap("claude", root=tmp_path)
    assert (tmp_path / "CLAUDE.md").read_text() == "# Project notes\n"
    assert not (tmp_path / ".claude").exists()


def test_claude_force_overwrites_existing_claude_md(tmp_path: Path) -> None:
    (tmp_path / "CLAUDE.md").write_text("# Project notes\n")
    write_agent_bootstrap("claude", brief=True, force=True, root=tmp_path)
    assert (tmp_path / "CLAUDE.md").read_text().startswith(CLAUDE_GUIDANCE_BEGIN)


def test_claude_append_adds_guidance_to_existing_claude_md(tmp_path: Path) -> None:
    (tmp_path / "CLAUDE.md").write_text("# Project notes\n\nKeep this.\n")
    write_agent_bootstrap("claude", append=True, root=tmp_path)

    text = (tmp_path / "CLAUDE.md").read_text()
    assert text.startswith("# Project notes\n\nKeep this.\n\n" + CLAUDE_GUIDANCE_BEGIN)
    assert text.count(CLAUDE_GUIDANCE_BEGIN) == 1
    assert (tmp_path / ".claude/skills/exodusii-querying/SKILL.md").exists()


def test_claude_append_refreshes_existing_guidance_block(tmp_path: Path) -> None:
    stale = f"# Notes\n\n{CLAUDE_GUIDANCE_BEGIN}\nstale\n{CLAUDE_GUIDANCE_END}\n\n## Footer\n"
    (tmp_path / "CLAUDE.md").write_text(stale)
    write_agent_bootstrap("claude", append=True, brief=True, root=tmp_path)

    text = (tmp_path / "CLAUDE.md").read_text()
    assert "stale" not in text
    assert text.startswith(f"# Notes\n\n{CLAUDE_GUIDANCE_BEGIN}\n# exodusii Guidance")
    assert text.endswith(f"{CLAUDE_GUIDANCE_END}\n\n## Footer\n")
    assert text.count(CLAUDE_GUIDANCE_BEGIN) == 1


def test_append_rejected_for_non_claude_targets(tmp_path: Path) -> None:
    with pytest.raises(ValueError, match="claude"):
        write_agent_bootstrap("generic", append=True, root=tmp_path)


def test_rerun_refreshes_existing_managed_files(tmp_path: Path) -> None:
    write_agent_bootstrap("opencode", root=tmp_path)
    bootstrap = tmp_path / ".agent/exodusii/BOOTSTRAP.md"
    skill = tmp_path / ".opencode/skills/exodusii-querying/SKILL.md"
    bootstrap.write_text("# exodusii Agent Bootstrap\n\nold\n")
    skill.write_text("---\nname: exodusii-querying\ndescription: old\n---\n\nold\n")

    write_agent_bootstrap("opencode", root=tmp_path)

    assert "old" not in bootstrap.read_text()
    assert "description: old" not in skill.read_text()


def test_refuses_to_overwrite_unmanaged_files(tmp_path: Path) -> None:
    index = tmp_path / ".agent/exodusii/INDEX.md"
    index.parent.mkdir(parents=True)
    index.write_text("# Someone else's index\n")

    with pytest.raises(FileExistsError, match="--force"):
        write_agent_bootstrap("generic", root=tmp_path)
    assert index.read_text() == "# Someone else's index\n"
    assert not (tmp_path / ".agent/exodusii/BOOTSTRAP.md").exists()

    write_agent_bootstrap("generic", force=True, root=tmp_path)
    assert index.read_text().startswith("# exodusii Agent Guide\n")


def test_unknown_target_rejected(tmp_path: Path) -> None:
    with pytest.raises(ValueError, match="unsupported agent bootstrap target"):
        write_agent_bootstrap("vim", root=tmp_path)


def test_cli_bootstrap_emits_json_summary(tmp_path: Path) -> None:
    code, payload = _run_json(["agent", "bootstrap", "claude", "-C", str(tmp_path)])
    assert code == 0
    assert payload["ok"] is True
    assert payload["target"] == "claude"
    assert payload["directory"] == str(tmp_path)
    assert payload["files"][0] == "CLAUDE.md"
    assert set(payload["files"]) == _files(tmp_path)


def test_cli_bootstrap_defaults_to_generic_in_cwd(tmp_path: Path, monkeypatch) -> None:
    monkeypatch.chdir(tmp_path)
    code, payload = _run_json(["agent", "bootstrap", "--brief"])
    assert code == 0
    assert payload["files"] == [".agent/exodusii/BOOTSTRAP.md"]
    assert (tmp_path / ".agent/exodusii/BOOTSTRAP.md").exists()


def test_cli_bootstrap_conflict_reports_json_error(tmp_path: Path) -> None:
    (tmp_path / "CLAUDE.md").write_text("# mine\n")
    stream = io.StringIO()
    code = main(["agent", "bootstrap", "claude", "-C", str(tmp_path)], file=stream)
    assert code == 1
    payload = json.loads(stream.getvalue())
    assert payload["ok"] is False
    assert payload["error"]["type"] == "FileExistsError"


def test_cli_agent_without_action_prints_usage() -> None:
    code, payload = _run_json(["agent"])
    assert code == 0
    assert "bootstrap" in payload["usage"]
